import { OBJECT_IDS, type ObjectId } from './types';

/**
 * Подбор объектов по смыслу. Интерфейс намеренно узкий: текст на входе, ранжированный
 * список объектов с объяснением на выходе. Реализацию можно заменить (например, на
 * эмбеддинги), не трогая остальной сервис. Объекты при этом не создаются и не меняются —
 * подбор только выбирает из десяти готовых.
 */
export interface Match {
  object: ObjectId;
  score: number;
  /** Слова запроса, по которым объект выбран. */
  hits: string[];
}

interface Entry {
  /** Основы названий: по ним объект находят в сценарии «по названиям». */
  names: string[];
  /** Смыслы: основа слова → вес. Основа сравнивается с началом слова запроса; «$» в конце — слово целиком. */
  concepts: Record<string, number>;
  meaning: string;
}

