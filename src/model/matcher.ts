export function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^a-zа-я0-9]+/i)
    .filter((t) => t.length > 1);
}

/** Основа сравнивается с началом слова; знак «$» в конце требует точного совпадения. */
function hit(token: string, stem: string): boolean {
  const s = stem.replace(/ё/g, 'е');
  return s.endsWith('$') ? token === s.slice(0, -1) : token.startsWith(s);
}

/** Сценарий 1: метафора или заголовок → объекты, подходящие по смыслу. */
export function matchByMeaning(text: string): Match[] {
  const tokens = tokenize(text);
  const out: Match[] = [];
  for (const object of OBJECT_IDS) {
    const entry = LEXICON[object];
    let score = 0;
    const hits = new Set<string>();
    for (const token of tokens) {
      let best = 0;
      // Прямое упоминание объекта сильнее любого смысла.
      if (entry.names.some((n) => hit(token, n))) best = 5;
      for (const [stem, weight] of Object.entries(entry.concepts)) {
        if (weight > best && hit(token, stem)) best = weight;
      }
      if (best) {
        score += best;
        hits.add(token);
      }
    }
    if (score > 0) out.push({ object, score, hits: [...hits] });
  }
  return out.sort((a, b) => b.score - a.score || OBJECT_IDS.indexOf(a.object) - OBJECT_IDS.indexOf(b.object));
}

/** Объекты для композиции: не больше трёх и только те, что не сильно уступают лучшему. */
export function pickByMeaning(text: string): Match[] {
  const ranked = matchByMeaning(text);
  if (!ranked.length) return [];
  return ranked.filter((m) => m.score >= ranked[0].score * 0.4).slice(0, 3);
}

export interface NameParse {
  objects: ObjectId[];
  /** Слова, которые не удалось сопоставить ни с одним объектом. */
  unknown: string[];
}

/** Сценарий 2: человек перечисляет названия компонентов. Повтор названия даёт повтор объекта. */
export function matchByNames(text: string): NameParse {
  const objects: ObjectId[] = [];
  const unknown: string[] = [];
  const skip = new Set(['на', 'цветами', 'цветы', 'цветов']);
  const tokens = tokenize(text);
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i];
    const found = OBJECT_IDS.find((id) => LEXICON[id].names.some((n) => hit(token, n)));
    if (found) {
      // «ваза с цветами» — одно название, а не ваза и ещё один букет.
      if (found === 'vase' && objects[objects.length - 1] === 'vase' && skip.has(token)) continue;
      objects.push(found);
    } else if (!skip.has(token) && !/^\d+$/.test(token)) {
      unknown.push(token);
    }
  }
  return { objects, unknown };
}
